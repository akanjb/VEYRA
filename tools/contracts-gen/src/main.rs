//! Generates `packages/contracts/src/generated` from the Rust DTOs in `veyra-app`.
//!
//! Usage:
//! - `veyra-contracts-gen`          regenerate the contracts package
//! - `veyra-contracts-gen --check`  fail if the committed contracts are out of date
//!
//! The command catalogue (`veyra_app::for_each_command!`) is the single source: every
//! command contributes its request/response types and an entry in `commands.ts`.

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use ts_rs::{Config, TS};

type BoxResult<T> = Result<T, Box<dyn Error>>;

const HEADER: &str = "// GENERATED by tools/contracts-gen from crates/veyra-app. Do not edit.\n";

/// One command as it appears in the generated TypeScript command map.
struct CommandEntry {
    name: &'static str,
    request: TypeRef,
    response: TypeRef,
}

/// A generated TypeScript type and the module that declares it.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord)]
struct TypeRef {
    name: String,
    module: String,
}

fn main() -> ExitCode {
    match run() {
        Ok(code) => code,
        Err(error) => {
            eprintln!("contracts-gen: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> BoxResult<ExitCode> {
    let check_only = std::env::args().skip(1).any(|arg| arg == "--check");
    let target = workspace_root()?.join("packages/contracts/src/generated");
    let staging = std::env::temp_dir().join(format!("veyra-contracts-{}", std::process::id()));
    recreate_dir(&staging)?;

    let outcome = generate(&staging).and_then(|()| {
        if check_only {
            check(&staging, &target)
        } else {
            replace(&staging, &target).map(|()| ExitCode::SUCCESS)
        }
    });
    fs::remove_dir_all(&staging)?;
    outcome
}

fn workspace_root() -> BoxResult<PathBuf> {
    Ok(Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()?)
}

fn type_ref<T: TS + 'static + ?Sized>(cfg: &Config) -> BoxResult<TypeRef> {
    let path = T::output_path().ok_or("command types must be exportable")?;
    let module = path
        .with_extension("")
        .to_str()
        .ok_or("non-UTF-8 output path")?
        .replace('\\', "/");
    Ok(TypeRef {
        name: T::name(cfg),
        module: format!("./{module}"),
    })
}

/// Writes every contract file into `dir`.
fn generate(dir: &Path) -> BoxResult<()> {
    let cfg = Config::new().with_out_dir(dir);
    let mut commands: Vec<CommandEntry> = Vec::new();

    macro_rules! export_commands {
        ($($name:ident($request:ty) -> $response:ty;)*) => {$(
            <$request as TS>::export_all(&cfg)?;
            <$response as TS>::export_all(&cfg)?;
            commands.push(CommandEntry {
                name: stringify!($name),
                request: type_ref::<$request>(&cfg)?,
                response: type_ref::<$response>(&cfg)?,
            });
        )*};
    }
    veyra_app::for_each_command!(export_commands);
    <veyra_app::ApiError as TS>::export_all(&cfg)?;

    let mut events: Vec<(&'static str, TypeRef)> = Vec::new();
    macro_rules! export_events {
        ($($name:expr => $payload:ty;)*) => {$(
            <$payload as TS>::export_all(&cfg)?;
            events.push(($name, type_ref::<$payload>(&cfg)?));
        )*};
    }
    veyra_app::for_each_event!(export_events);

    fs::write(dir.join("commands.ts"), render_commands(&commands))?;
    fs::write(dir.join("events.ts"), render_events(&events))?;
    fs::write(dir.join("index.ts"), render_index(dir)?)?;
    Ok(())
}

fn render_events(events: &[(&str, TypeRef)]) -> String {
    let mut imports: Vec<&TypeRef> = events.iter().map(|(_, payload)| payload).collect();
    imports.sort();
    imports.dedup();

    let mut out = String::from(HEADER);
    for import in imports {
        let _ = writeln!(
            out,
            "import type {{ {} }} from \"{}\";",
            import.name, import.module
        );
    }
    out.push_str("\n/** Payload of every event the core emits, keyed by event name. */\n");
    out.push_str("export interface EventMap {\n");
    for (name, payload) in events {
        let _ = writeln!(out, "  \"{name}\": {};", payload.name);
    }
    out.push_str("}\n\nexport type EventName = keyof EventMap;\n\n");
    out.push_str("export const EVENT_NAMES = [\n");
    for (name, _) in events {
        let _ = writeln!(out, "  \"{name}\",");
    }
    out.push_str("] as const satisfies readonly EventName[];\n");
    out
}

fn render_commands(commands: &[CommandEntry]) -> String {
    let mut imports: Vec<&TypeRef> = commands
        .iter()
        .flat_map(|c| [&c.request, &c.response])
        .collect();
    imports.sort();
    imports.dedup();

    let mut out = String::from(HEADER);
    for import in imports {
        let _ = writeln!(
            out,
            "import type {{ {} }} from \"{}\";",
            import.name, import.module
        );
    }
    out.push_str("\n/** Request and response types of every command, keyed by command name. */\n");
    out.push_str("export interface CommandMap {\n");
    for command in commands {
        let _ = writeln!(
            out,
            "  {}: {{ request: {}; response: {} }};",
            command.name, command.request.name, command.response.name
        );
    }
    out.push_str("}\n\nexport type CommandName = keyof CommandMap;\n\n");
    out.push_str("export const COMMAND_NAMES = [\n");
    for command in commands {
        let _ = writeln!(out, "  \"{}\",", command.name);
    }
    out.push_str("] as const satisfies readonly CommandName[];\n");
    out
}

/// Barrel file re-exporting every generated module.
fn render_index(dir: &Path) -> BoxResult<String> {
    let mut modules = ts_modules(dir)?;
    modules.retain(|m| !matches!(m.as_str(), "index" | "commands" | "events"));
    let mut out = String::from(HEADER);
    for module in modules {
        let _ = writeln!(out, "export type * from \"./{module}\";");
    }
    out.push_str("export * from \"./commands\";\n");
    out.push_str("export * from \"./events\";\n");
    Ok(out)
}

/// Sorted module names (file stems) of the `.ts` files directly inside `dir`.
fn ts_modules(dir: &Path) -> BoxResult<Vec<String>> {
    let mut names = Vec::new();
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|ext| ext == "ts")
            && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
        {
            names.push(stem.to_owned());
        }
    }
    names.sort();
    Ok(names)
}

fn check(generated: &Path, committed: &Path) -> BoxResult<ExitCode> {
    let expected = ts_modules(generated)?;
    let actual = if committed.exists() {
        ts_modules(committed)?
    } else {
        Vec::new()
    };
    let mut stale: Vec<String> = Vec::new();

    for module in &expected {
        let file = format!("{module}.ts");
        let fresh = fs::read_to_string(generated.join(&file))?;
        match fs::read_to_string(committed.join(&file)) {
            Ok(current) if current == fresh => {}
            Ok(_) => stale.push(format!("changed: {file}")),
            Err(_) => stale.push(format!("missing: {file}")),
        }
    }
    stale.extend(
        actual
            .iter()
            .filter(|m| !expected.contains(m))
            .map(|m| format!("unexpected: {m}.ts")),
    );

    if stale.is_empty() {
        eprintln!("contracts-gen: contracts are up to date");
        return Ok(ExitCode::SUCCESS);
    }
    eprintln!("contracts-gen: contracts are out of date — run `pnpm contracts:generate`");
    for line in stale {
        eprintln!("  {line}");
    }
    Ok(ExitCode::FAILURE)
}

fn replace(generated: &Path, target: &Path) -> BoxResult<()> {
    recreate_dir(target)?;
    for module in ts_modules(generated)? {
        let file = format!("{module}.ts");
        fs::copy(generated.join(&file), target.join(&file))?;
    }
    eprintln!("contracts-gen: wrote packages/contracts/src/generated");
    Ok(())
}

fn recreate_dir(dir: &Path) -> BoxResult<()> {
    if dir.exists() {
        fs::remove_dir_all(dir)?;
    }
    fs::create_dir_all(dir)?;
    Ok(())
}
